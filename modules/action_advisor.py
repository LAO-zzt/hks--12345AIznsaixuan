def _match_department(event_type: str):
    """根据事件类型匹配部门与动作；未命中返回 None。"""
    if not event_type or event_type.startswith("（"):
        return None
    for key, dept, action in DEPT_RULES:
        if key in event_type or event_type in key:
            return dept, action
    return None


def advise_actions(events: list) -> list:
    """
    为每个事件补充处置建议字段：
    action_department / action_advice / monitor_required / is_key_event。
    """
    for ev in events:
        matched = _match_department(ev.get("event_type", ""))
        if matched:
            ev["action_department"], ev["action_advice"] = matched
        else:
            # 不得伪造部门归属
            ev["action_department"] = "需人工研判"
            ev["action_advice"] = "暂未匹配到对应处置部门，建议人工研判后分派。"

        # 持续监控：趋势上升 或 高关注 即建议持续监控
        ev["monitor_required"] = "是" if (
            ev.get("trend") == "上升" or ev.get("risk_level") == "高关注"
        ) else "否"

        # 重点事件列表：高关注即纳入
        ev["is_key_event"] = "是" if ev.get("risk_level") == "高关注" else "否"
    return events
